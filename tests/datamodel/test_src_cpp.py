import dataclasses
import pathlib
import re
import subprocess

import pydantic
import pytest

from experiment_datadefinitions.datamodel import unittests_nested, unittests_simple
from experiment_datadefinitions.renderer import renderer_cpp

DIRECTORY_OF_THIS_FILE = pathlib.Path(__file__).parent
DIRECTORY_SRC_CPP = DIRECTORY_OF_THIS_FILE / "src_cpp"

MODEL_PID_CONTROLLER = unittests_simple.ModelPidController(
    name="Axis W", value=42, i_param=3.14
)
# The generated initializer references the variable 'pid_controller' for both axes
MODEL_SYSTEM_DUAL = unittests_nested.ModelSystemDual(
    axis_x=MODEL_PID_CONTROLLER,
    axis_y=MODEL_PID_CONTROLLER,
    debuglevel=3,
)
# The generated initializer references the variable 'pid_controller' for both controllers
MODEL_SYSTEM_LIST = unittests_nested.ModelSystemList(
    controllers=[MODEL_PID_CONTROLLER, MODEL_PID_CONTROLLER],
    debuglevel=3,
)


@dataclasses.dataclass(frozen=True)
class ParameterSrcCpp:
    model: pydantic.BaseModel
    expected_size: int

    @property
    def renderer(self) -> renderer_cpp.RendererCPP:
        return renderer_cpp.RendererCPP(model=self.model)

    @property
    def identifier(self) -> str:
        """
        This will be the parameter [...] used by pytest.
        """
        return self.renderer.cpp_filename


parameters_src_cpp = [
    # The models below include the headers generated by MODEL_PID_CONTROLLER: Keep this order!
    ParameterSrcCpp(model=MODEL_PID_CONTROLLER, expected_size=38),
    ParameterSrcCpp(model=MODEL_SYSTEM_DUAL, expected_size=80),
    ParameterSrcCpp(model=MODEL_SYSTEM_LIST, expected_size=80),
]


@pytest.mark.parametrize(
    "parameter",
    parameters_src_cpp,
    ids=lambda parameter: parameter.identifier,
)
def test_src_cpp(parameter: ParameterSrcCpp) -> None:
    assert isinstance(parameter, ParameterSrcCpp)

    renderer = parameter.renderer
    executable = f"generated_dump_values_{renderer.cpp_filename}"

    def generate_compile() -> None:
        """
        TODO: Clearer interface
        """

        def generate(filename: pathlib.Path, source: str) -> None:
            filename.write_text(source)

        generate(
            DIRECTORY_SRC_CPP / renderer.filename_struct,
            renderer.render_cpp_struct(),
        )
        generate(
            DIRECTORY_SRC_CPP / renderer.filename_initializer,
            renderer.render_cpp_initializer(),
        )

        subprocess.run(
            [
                "g++",
                "-Wall",
                "-Wextra",
                f"dump_values_{renderer.cpp_filename}.cpp",
                "-o",
                executable,
            ],
            cwd=DIRECTORY_SRC_CPP,
            check=True,
        )

    def run() -> bytes:
        """
        TODO: Clearer interface
        """
        result = subprocess.run(
            [f"./{executable}"],
            cwd=DIRECTORY_SRC_CPP,
            check=True,
            capture_output=True,
            text=True,
        )

        stdout = result.stdout.strip()
        match = re.fullmatch(r">0x(?P<hexstring>[0-9A-F]+)<", stdout)
        assert match is not None
        hexstring = match.group("hexstring")
        serialized = bytes.fromhex(hexstring)
        return serialized

    generate_compile()
    serialized = run()

    assert len(serialized) == parameter.expected_size
    assert renderer.serialize_to_cpp(model=parameter.model) == serialized

    model3 = renderer.deserialize_from_cpp(serizalized=serialized)
    assert isinstance(model3, type(parameter.model))
    assert renderer.serialize_to_cpp(model=model3) == serialized
