import pathlib
import re
import subprocess

import pydantic
import pytest

from experiment_datadefinitions.datamodel import unittests_nested, unittests_simple
from experiment_datadefinitions.renderer import renderer_cpp

DIRECTORY_OF_THIS_FILE = pathlib.Path(__file__).parent
DIRECTORY_SRC_CPP = DIRECTORY_OF_THIS_FILE / "src_cpp"

MODEL_PID_CONTROLLER = unittests_simple.ModelPidController(
    name="Axis W", value=42, i_param=3.14
)
# The generated initializer references the variable 'pid_controller' for both axes
MODEL_DUAL = unittests_nested.ModelSystemDual(
    axis_x=MODEL_PID_CONTROLLER,
    axis_y=MODEL_PID_CONTROLLER,
    debuglevel=3,
)


@pytest.mark.parametrize(
    ("name", "expected_size", "model"),
    [
        # "dual" includes the headers generated by "pid_controller": Keep this order!
        ("pid_controller", 40, MODEL_PID_CONTROLLER),
        ("dual", 84, MODEL_DUAL),
    ],
)
def test_src_cpp(name: str, expected_size: int, model: pydantic.BaseModel) -> None:
    renderer = renderer_cpp.RendererCPP(model=model)
    executable = f"generated_dump_values_{name}"

    def generate_compile() -> None:
        """
        TODO: Clearer interface
        """

        def generate(filename: pathlib.Path, source: str) -> None:
            filename.write_text(source)

        generate(
            DIRECTORY_SRC_CPP / f"generated_{name}_struct.hpp",
            renderer.render_cpp_struct(),
        )
        generate(
            DIRECTORY_SRC_CPP / f"generated_{name}_initializer.hpp",
            renderer.render_cpp_initializer(),
        )

        subprocess.run(
            ["g++", "-Wall", "-Wextra", f"dump_values_{name}.cpp", "-o", executable],
            cwd=DIRECTORY_SRC_CPP,
            check=True,
        )

    def run() -> bytes:
        """
        TODO: Clearer interface
        """
        result = subprocess.run(
            [f"./{executable}"],
            cwd=DIRECTORY_SRC_CPP,
            check=True,
            capture_output=True,
            text=True,
        )

        stdout = result.stdout.strip()
        match = re.fullmatch(r">0x(?P<hexstring>[0-9A-F]+)<", stdout)
        assert match is not None
        hexstring = match.group("hexstring")
        serialized = bytes.fromhex(hexstring)
        return serialized

    generate_compile()
    serialized = run()

    assert len(serialized) == expected_size
    assert renderer.serialize_to_cpp(model=model) == serialized

    model3 = renderer.deserialize_from_cpp(serizalized=serialized)
    assert isinstance(model3, type(model))
    assert renderer.serialize_to_cpp(model=model3) == serialized
